//! Task 10 (2FA backend plan) — end-to-end integration suite for the TOTP
//! 2FA flow: forced enrollment, enroll/verify, login challenge, replay
//! rejection, lockout, backup codes, the no-2FA fast path, and the
//! purpose-token/access-token boundary.
//!
//! Every test drives the REAL HTTP surface (`support::router`, the same
//! `AppState`/`build_router` production wiring the other dashboard suites
//! use) against a fresh `#[sqlx::test]` Postgres database — no mocking of
//! `user_repo`, `totp`, or the handlers themselves. TOTP codes are computed
//! independently via the `totp-rs` crate directly (not via
//! `secureprompt_api::auth::totp`'s private `#[cfg(test)]` `code_at` helper,
//! which is internal to that module) against the `secret_b32` the `/enroll`
//! response returns — so a passing test proves the server's `verify_code`
//! genuinely accepts a code generated by an independent RFC 6238
//! implementation, not merely a fixture the server also produced.
//!
//! Requires a reachable Postgres (`DATABASE_URL`) AND Redis (`REDIS_URL`,
//! defaults to `redis://localhost:6379`) — `docker compose up -d postgres
//! redis`. Also requires `KMS_FILE_KEY` (see `.env`) since `/2fa/enroll`
//! encrypts the TOTP secret via `AppState.kms` before persisting it.

