// ================================================================
// Scenario 8: an enrollment_token / challenge_token cannot authorize a
// normal protected route.
// ================================================================

#[sqlx::test]
async fn purpose_tokens_cannot_access_protected_routes(pool: PgPool) -> sqlx::Result<()> {
    let account = seed_account(&pool, "admin").await?;
    let router = support::router(pool);

    // enrollment_token
    let (_status, body) = login(&router, &account.email).await;
    let enrollment_token = body["enrollment_token"]
        .as_str()
        .expect("enrollment_token")
        .to_owned();
    let status = get_status_with_bearer(&router, "/v1/secure-mode", &enrollment_token).await;
    assert_eq!(
        status,
        StatusCode::UNAUTHORIZED,
        "an enrollment_token must not authorize GET /v1/secure-mode"
    );

    // challenge_token (needs a confirmed account first)
    let (_secret, _backup_codes) = enroll_and_confirm(&router, &account).await;
    let (_status2, body2) = login(&router, &account.email).await;
    let challenge_token = body2["challenge_token"]
        .as_str()
        .expect("challenge_token")
        .to_owned();
    let status2 = get_status_with_bearer(&router, "/v1/secure-mode", &challenge_token).await;
    assert_eq!(
        status2,
        StatusCode::UNAUTHORIZED,
        "a challenge_token must not authorize GET /v1/secure-mode"
    );
    Ok(())
}
